const featured = ['BG', 'RS', 'GR', 'RO', 'MK', 'TR', 'DE', 'GB', 'US', 'FR', 'IT', 'ES'];
const aliases = {
  DE: ['Germany', 'Deutschland'],
  GB: ['Англия', 'Великобритания', 'UK', 'Great Britain', 'England', 'Scotland', 'Wales'],
  GR: ['Hellas', 'Ελλάδα'],
  KR: ['Република Корея'],
  MK: ['Македония', 'Macedonia'],
  TR: ['Türkiye'],
  UA: ['Україна'],
  US: ['САЩ', 'Америка', 'USA', 'United States of America'],
};
const displayNames = typeof Intl.DisplayNames === 'function'
  ? new Intl.DisplayNames(['bg'], { type: 'region', fallback: 'none' })
  : null;

export const countries = catalog.map(([code, originalName, count]) => ({
  code,
  name: displayNames?.of(code) ?? originalName,
  originalName,
  flag: new URL(`./assets/flags/${code.toLowerCase()}.png`, import.meta.url).href,
  count,
})).sort((a, b) => {
  const rankA = featured.indexOf(a.code);
  const rankB = featured.indexOf(b.code);
  if (rankA >= 0 || rankB >= 0) {
    return (rankA < 0 ? Infinity : rankA) - (rankB < 0 ? Infinity : rankB);
  }
  return a.name.localeCompare(b.name, 'bg');
});

export function normalizeSearch(value) {
  return value.normalize('NFKD').replace(/([\p{Script=Latin}\p{Script=Cyrillic}])\p{M}+/gu, '$1').trim().toLocaleLowerCase('bg');
}

export function countryMatches(country, query, localizedName = country.name) {
  const key = normalizeSearch(query);
  return [country.code, localizedName, country.name, country.originalName, ...(aliases[country.code] ?? [])]
    .some(value => normalizeSearch(value).includes(key));
}

const countryCodes = new Set(countries.map(country => country.code));
const pending = new Map();

export function catalogURL(code) {
  return new URL(`./data/${code.toLowerCase()}.json`, import.meta.url);
}

export function loadStations(code) {
  const country = String(code).toUpperCase();
  if (!countryCodes.has(country)) {
    return Promise.reject(new RangeError(`Непознат код на държава: ${country}`));
  }
  if (!pending.has(country)) {
    const path = catalogURL(country);
    pending.set(country, fetch(path).then(response => {
      if (!response.ok) {
        throw new Error(`Каталогът временно е недостъпен (HTTP ${response.status}).`);
      }
      return response.json();
    }).catch(error => {
      pending.delete(country);
      throw error;
    }));
  }
  return pending.get(country);
}
